def make_db(path: Path, wal: bool = False) -> sqlite3.Connection:
    con = sqlite3.connect(path)
    if wal:
        con.execute("PRAGMA journal_mode=WAL")
        con.execute("PRAGMA wal_autocheckpoint=0")
    con.executescript("""
        CREATE TABLE transcript_events (session_id TEXT, seq INTEGER, event_json TEXT, event_zstd BLOB, created_at INTEGER);
        CREATE TABLE session_windows (session_id TEXT, session_key TEXT, channel TEXT, chat_type TEXT, display_name TEXT,
                                      model TEXT, model_provider TEXT, started_at INTEGER);
        CREATE TABLE session_nodes (session_key TEXT, current_session_id TEXT, label TEXT, display_name TEXT);
        CREATE TABLE session_transcript_archives (session_id TEXT, session_key TEXT, archive_name TEXT, archive_blob BLOB,
                                                  encoding TEXT, reason TEXT, created_at INTEGER);
    """)
    z = zstandard.ZstdCompressor()
    for seq, ev in enumerate(oc_events()):
        text = json.dumps(ev)
        if seq % 2:  # mix plain and compressed rows
            con.execute("INSERT INTO transcript_events VALUES (?,?,?,?,?)", ("oc-1", seq, None, z.compress(text.encode()), seq))
        else:
            con.execute("INSERT INTO transcript_events VALUES (?,?,?,?,?)", ("oc-1", seq, text, None, seq))
    con.execute("INSERT INTO session_windows VALUES ('oc-1', 'agent:work:telegram:direct:1', 'telegram', 'direct', "
                "'Files', 'claude-sonnet-5', 'anthropic', 1782286260000)")
    con.execute("INSERT INTO session_nodes VALUES ('agent:work:telegram:direct:1', 'oc-1', 'My files', NULL)")
    gone = [dict(e, id=e.get("id")) for e in oc_events()[:5]]
    gone[0]["id"] = "oc-2"
    con.execute("INSERT INTO session_transcript_archives VALUES (?,?,?,?,?,?,?)",
                ("oc-2", "agent:work:whatsapp:direct:2", "oc-2.jsonl.deleted.2026-06-25T08-00-00Z.zst",
                 z.compress(jsonl(gone)), "zstd", "manual", 1782374400000))
    con.commit()
    return con


def test_openclaw_sqlite(tmp_path):
    make_db(tmp_path / "a.sqlite").close()
    parser = OpenClawParser()
    convs = parser.parse((tmp_path / "a.sqlite").read_bytes(), "openclaw-agent.sqlite")
    assert not parser.warnings
    live, deleted = sorted(convs, key=lambda c: c.meta.get("archive", ""))
    assert live.title == "My files" and live.meta["channel"] == "telegram" and live.meta["agent"] == "work"
    assert live.meta["session_key"] == "agent:work:telegram:direct:1"
    assert sum(len(m.blocks) for m in live.messages) >= 9  # compressed rows were decoded
    assert deleted.meta["archive"] == "deleted" and deleted.meta["archive_reason"] == "manual"
    assert deleted.meta["session_id"] == "oc-2"
    assert sniff_parser((tmp_path / "a.sqlite").read_bytes(), "x.sqlite").name == "openclaw"
    # an unrelated SQLite file
    other = tmp_path / "b.sqlite"
    sqlite3.connect(other).execute("CREATE TABLE t (x)").connection.close()
    p = OpenClawParser()
    assert p.parse(other.read_bytes(), "b.sqlite") == [] and "no transcript_events" in p.warnings[0]


def test_openclaw_sqlite_reads_the_write_ahead_log(tmp_path):
    db = tmp_path / "live.sqlite"
    con = make_db(db, wal=True)  # still open: the rows only exist in live.sqlite-wal
    try:
        main_only = OpenClawParser().parse(db.read_bytes(), "live.sqlite")
        parser = OpenClawParser()
        parser.companions = {"-wal": Path(f"{db}-wal").read_bytes()}
        with_wal = parser.parse(db.read_bytes(), "live.sqlite")
    finally:
        con.close()
    assert main_only == [] and len(with_wal) == 2


