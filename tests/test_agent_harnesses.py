def cc_row(typ, uid, parent=None, **fields):
    return {"parentUuid": parent, "isSidechain": False, "userType": "external", "cwd": "/home/alice/proj",
            "sessionId": "s-1", "version": "2.1.90", "gitBranch": "main", "type": typ, "uuid": uid,
            "timestamp": f"2026-06-01T10:00:{int(uid[1:]):02d}.000Z", **fields}


def cc_jsonl(rows):
    return "".join(json.dumps(r) + "\n" for r in rows).encode()


def assistant(uid, msg_id, block, model="claude-sonnet-5", **extra):
    return cc_row("assistant", uid, message={"id": msg_id, "role": "assistant", "model": model, "content": [block]}, **extra)


def user(uid, content, **extra):
    return cc_row("user", uid, message={"role": "user", "content": content}, **extra)


