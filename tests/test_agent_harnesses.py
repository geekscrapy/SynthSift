def test_claude_code_session_structure():
    raw = cc_jsonl(CC_ROWS) + b'{"type": "user", "trunc'  # a live file copied mid-write
    parser = ClaudeCodeParser()
    main, sub = parser.parse(raw, "s-1.jsonl")
    assert parser.warnings == ["skipped 1 unreadable line(s)"]
    assert main.title == "Fix the flaky test" and main.model == "claude-sonnet-5"
    assert main.meta["cwd"] == "/home/alice/proj" and main.meta["project"] == "proj" and main.meta["git_branch"] == "main"

    # streamed rows of one API message become one message
    a = main.messages[1]
    assert a.role == "assistant" and [b.kind for b in a.blocks] == ["thinking", "text", "tool_call"]
    assert a.blocks[2].tool_name == "Read" and a.blocks[2].arguments == {"file_path": "tests/test_io.py"}

    # tool result linked to its call; the harness reminder is split out
    res = main.messages[2]
    assert res.role == "tool" and res.blocks[0].tool_name == "Read" and "system-reminder" not in res.blocks[0].text
    assert main.messages[3].role == "system" and main.messages[3].meta["kind"] == "system_reminder"

    kinds = [(m.role, m.meta.get("kind")) for m in main.messages]
    assert ("user", "command") in kinds and ("system", "command_output") in kinds
    assert ("system", "meta") in kinds and ("user", "queued_prompt") in kinds
    assert ("system", "compact_boundary") in kinds and ("system", "compact_summary") in kinds
    assert ("system", "api_error") in kinds
    cmd = next(m for m in main.messages if m.meta.get("kind") == "command")
    assert cmd.blocks[0].text == "/model opus"

    # "!" bash mode: a shell command the user ran, with its output
    shell = next(m for m in main.messages if m.meta.get("kind") == "user_shell")
    call = shell.blocks[0]
    assert call.kind == "tool_call" and call.tool_name == "user_shell" and call.arguments == {"command": "git status"}
    out = main.messages[main.messages.index(shell) + 1].blocks[0]
    assert out.kind == "tool_result" and out.tool_call_id == call.tool_call_id and out.text == "M tests/test_io.py"

    # no duplicate from the repeated uuid
    assert sum(1 for m in main.messages for b in m.blocks if b.text == "duplicate row") == 0

    # the sub-agent is its own conversation
    assert sub.meta["subagent"] and sub.meta["agent_id"] == "ag1" and sub.meta["parent_session_id"] == "s-1"
    assert sub.title.startswith("Sub-agent: Search the repo") and sub.model == "claude-haiku-4-5"
    assert [m.role for m in sub.messages] == ["user", "assistant", "tool"]


