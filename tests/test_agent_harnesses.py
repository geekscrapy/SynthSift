def test_ingest_agent_state_folders_and_archives(tmp_path):
    make_db(tmp_path / "db.sqlite").close()
    blob = zstandard.ZstdCompressor().compress(jsonl(oc_events()))
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        # a zip of the raw hidden folders: user comes from the Claude Code project path
        zf.writestr(".claude/projects/-home-alice-proj/s-1.jsonl", cc_jsonl(CC_ROWS))
        zf.writestr(".claude/settings.json", '{\n  "model": "opus"\n}\n')
        zf.writestr("srv/max/openclaw/agents/work/agent/openclaw-agent.sqlite", (tmp_path / "db.sqlite").read_bytes())
        zf.writestr("srv/max/openclaw/agents/work/sessions/oc-9.jsonl.deleted.2026-06-25T08-00-00Z.zst", blob)
        zf.writestr("srv/max/openclaw/agents/work/sessions/sessions.json", '{\n  "a": {}\n}\n')
        zf.writestr("srv/max/openclaw/agents/work/sessions/oc-9.jsonl.lock", '{"pid": 1}')
    rep = read_zip(buf.getvalue(), "ds")
    assert not rep.warnings
    got = sorted((c.host, c.user, c.harness, c.meta.get("archive", "")) for c in rep.conversations)
    assert got == [("srv", "max", "openclaw", ""), ("srv", "max", "openclaw", "deleted"), ("srv", "max", "openclaw", "deleted"),
                   ("unknown-host", "alice", "claude_code", ""), ("unknown-host", "alice", "claude_code", "")]


def test_samples_include_every_agent():
    rep = read_zip((ROOT / "samples" / "synthsift-samples.zip").read_bytes(), "s")
    assert not rep.warnings
    by_harness = {}
    for c in rep.conversations:
        by_harness.setdefault(c.harness, []).append(c)
    assert len(by_harness["claude_code"]) == 4 and len(by_harness["openclaw"]) == 4
    assert len(by_harness["gemini"]) == 4 and len(by_harness["antigravity"]) == 3
    assert {c.meta.get("app") for c in by_harness["antigravity"]} == {"Antigravity CLI", "Antigravity IDE", None}
    titles = {c.display_title for c in by_harness["openclaw"]}
    assert {"Groceries & dentist", "#homelab"} <= titles


